// ── Match logic ────────────────────────────────────────────────────────────
const MATCH_THRESHOLD = 0.5   // show if user has ≥ 50% of required ingredients

export function matchRecipes(selectedSet) {
  const scored = RECIPES.map(recipe => {
    const needed = recipe.requiredIngredients
    const have   = needed.filter(id => selectedSet.has(id))
    const pct    = needed.length > 0 ? have.length / needed.length : 0
    return {
      recipe,
      have,
      missing: needed.filter(id => !selectedSet.has(id)),
      pct,
    }
  }).sort((a, b) => b.pct - a.pct)

  const matches = scored.filter(s => s.pct >= MATCH_THRESHOLD)

  if (matches.length === 0) {
    return { results: scored.slice(0, 5), isFallback: true }
  }
  return { results: matches, isFallback: false }
}
